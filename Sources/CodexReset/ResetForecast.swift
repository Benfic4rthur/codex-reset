import Foundation

enum ResetCountdown {
    static func remaining(until deadline: Date, at now: Date) -> String? {
        let seconds = deadline.timeIntervalSince(now)
        guard seconds > 0 else { return nil }
        let minutes = max(1, Int(seconds / 60))
        let hours = minutes / 60
        if hours >= 24 {
            return "\(hours / 24)d \(hours % 24)h"
        }
        let remainder = minutes % 60
        return hours > 0 ? "\(hours)h \(String(format: "%02d", remainder))m" : "\(remainder)m"
    }
}

struct EstimatedResetWindow: Sendable {
    let startsAt: Date
    let endsAt: Date

    func presentation(at now: Date, isSmallSample: Bool = false) -> (headline: String, caption: String) {
        guard let end = ResetCountdown.remaining(until: endsAt, at: now) else {
            return ("Janela encerrada", "Aguardando novos dados")
        }
        guard let start = ResetCountdown.remaining(until: startsAt, at: now) else {
            if isSmallSample {
                return ("Dentro da janela\nAté \(end)", "Estimativa · poucos dados")
            }
            return ("Dentro da janela", "Estimativa: até \(end)")
        }
        return ("Entre \(start)\ne \(end)", isSmallSample ? "Estimativa · poucos dados" : "Estimativa histórica")
    }
}

/// An announced extra reset that has not yet been observed as applied.
/// `scheduledFor` can be nil, and a passed time does not prove execution.
struct ScheduledResetAnnouncement: Sendable {
    let announcedAt: Date
    let scheduledFor: Date?
    let resetType: String
    let text: String
    let sourceURL: URL
}

struct ResetForecast: Sendable {
    /// Latest reset observed by the source or in this account.
    let latest: Date

    /// Historical estimate in 0...1 for an extra reset within seven days.
    /// This is not an OpenAI promise or a personal quota renewal time.
    let probabilityNext7Days: Double?

    /// Absolute historical bounds anchored to the latest observed reset.
    /// Refreshing the same sample must not reanchor these deadlines to query time.
    let estimatedWindow: EstimatedResetWindow?
    let sampleSize: Int
    var hasSmallSample: Bool { sampleSize < 12 }

    /// Timestamp generated by the data source, rather than the device clock.
    let fetchedAt: Date
    let scheduledReset: ScheduledResetAnnouncement?
    let sourceURL: URL
    /// Source intervals only; a personal renewal never changes the sample.
    var historicalIntervals: [TimeInterval] = []

    func reconcilingQuotaReset(at observedAt: Date?) -> ResetForecast {
        let anchor = max(latest, observedAt ?? latest)
        let pending = scheduledReset.flatMap { announcement in
            announcement.resetType != "regular" || (announcement.scheduledFor ?? announcement.announcedAt) > anchor
                ? announcement : nil
        }
        return ResetForecast(latest: anchor, probabilityNext7Days: probabilityNext7Days,
            estimatedWindow: anchor == latest ? estimatedWindow
                : ResetForecastService.estimatedWindow(since: anchor, intervals: historicalIntervals),
            sampleSize: sampleSize, fetchedAt: fetchedAt, scheduledReset: pending,
            sourceURL: sourceURL, historicalIntervals: historicalIntervals)
    }

    func presentation(at now: Date) -> (headline: String, caption: String) {
        if let announcement = scheduledReset {
            if let date = announcement.scheduledFor {
                if let countdown = ResetCountdown.remaining(until: date, at: now) {
                    return ("Em \(countdown)", "Anúncio verificado na fonte")
                }
                return ("Horário anunciado passou", "Aguardando confirmação")
            }
            return ("Reset extra anunciado", "Anúncio verificado na fonte")
        }
        if let window = estimatedWindow {
            return window.presentation(at: now, isSmallSample: hasSmallSample)
        }
        return ("Sem estimativa", "Histórico insuficiente")
    }
}

enum ResetForecastError: LocalizedError {
    case invalidResponse
    case unavailable(Int)
    case noObservedResets

    var errorDescription: String? {
        switch self {
        case .invalidResponse:
            return "A fonte de resets retornou dados inválidos."
        case .unavailable(let code):
            return "A fonte de resets está indisponível (HTTP \(code))."
        case .noObservedResets:
            return "Ainda não há resets extraordinários observados para calcular a estimativa."
        }
    }
}

enum ResetForecastService {
    static let sourceURL = URL(string: "https://codex-resets.com/")!

    // Restrict the calculation to the last 30 days. Six intervals permit a
    // descriptive estimate; fewer than twelve are identified as a small sample.
    private static let lookbackDays = 30.0
    private static let minimumSampleSize = 6
    static let refreshInterval: TimeInterval = 2 * 60 * 60
    private static let secondsPerDay = 86_400.0

    // These posts only awarded a banked reset, although the third-party API
    // currently labels them "regular". They did not apply an immediate reset.
    private static let bankedOnlyMislabels: Set<String> = [
        "2076735790567338203", // July 13, 2026
        "2076418567143408112"  // July 12, 2026
    ]

    static func fetch() async throws -> ResetForecast {
        let status: StatusResponse = try await request(
            URL(string: "https://codex-resets.com/api/v1/status")!
        )
        let allResets = try await fetchHistory()
        // The status endpoint can refresh before the paginated history cache.
        // Prefer the newest observed event from either response.
        let candidates = allResets + [status.data.latestReset].compactMap { $0 }
        let applied = Array(Dictionary(candidates.map { ($0.id, $0) }, uniquingKeysWith: { first, _ in first }).values)
            .filter { $0.resetType == "regular" && !bankedOnlyMislabels.contains($0.id) }
            .sorted { $0.announcedAt < $1.announcedAt }

        guard let latest = applied.last?.announcedAt else {
            throw ResetForecastError.noObservedResets
        }

        let now = Date()
        let gaps = recentIntervals(from: applied.map(\.announcedAt), at: now)
        let age = max(0, now.timeIntervalSince(latest))
        let comparableGaps = gaps.filter { $0 > age }.sorted()

        let probability: Double?
        if comparableGaps.count >= minimumSampleSize {
            let withinWeek = comparableGaps.filter { $0 <= age + 7 * secondsPerDay }.count
            // Add-one smoothing avoids presenting 0% or 100% certainty from a
            // small, discretionary set of historical announcements.
            probability = (Double(withinWeek) + 1) / (Double(comparableGaps.count) + 2)
        } else {
            probability = nil
        }

        return ResetForecast(
            latest: latest,
            probabilityNext7Days: probability,
            estimatedWindow: estimatedWindow(since: latest, intervals: gaps),
            sampleSize: gaps.count,
            fetchedAt: status.meta.generatedAt,
            scheduledReset: verifiedAnnouncement(status.data.scheduledReset),
            sourceURL: sourceURL,
            historicalIntervals: gaps
        )
    }

    private static func fetchHistory() async throws -> [ResetRecord] {
        var records: [ResetRecord] = []
        var cursor: String?
        var seenCursors: Set<String> = []
        let cutoff = Date().addingTimeInterval(-lookbackDays * secondsPerDay)

        repeat {
            var components = URLComponents(string: "https://codex-resets.com/api/v1/resets")!
            components.queryItems = [
                URLQueryItem(name: "limit", value: "100"),
                URLQueryItem(name: "order", value: "desc")
            ]
            if let cursor {
                components.queryItems?.append(URLQueryItem(name: "cursor", value: cursor))
            }
            guard let url = components.url else { throw ResetForecastError.invalidResponse }
            let page: ResetListResponse = try await request(url)
            records.append(contentsOf: page.data)

            // Stop paging once the response crosses the 30-day cutoff.
            if page.data.last.map({ $0.announcedAt < cutoff }) == true {
                break
            }
            guard page.pagination.hasMore, let next = page.pagination.nextCursor,
                  seenCursors.insert(next).inserted else {
                break
            }
            cursor = next
        } while true

        return records
    }

    private static func verifiedAnnouncement(_ record: ScheduledResetRecord?) -> ScheduledResetAnnouncement? {
        guard let record,
              record.source.type == "x_post",
              record.source.author == "thsottiaux",
              let url = record.source.url,
              url.scheme == "https",
              url.host?.lowercased() == "x.com" else {
            return nil
        }
        return ScheduledResetAnnouncement(
            announcedAt: record.announcedAt,
            scheduledFor: record.scheduledFor,
            resetType: record.resetType,
            text: record.text,
            sourceURL: url
        )
    }

    static func recentIntervals(from resetDates: [Date], at now: Date) -> [TimeInterval] {
        let cutoff = now.addingTimeInterval(-lookbackDays * secondsPerDay)
        let recent = resetDates.filter { $0 >= cutoff && $0 <= now }.sorted()
        return zip(recent, recent.dropFirst()).compactMap {
            let gap = $1.timeIntervalSince($0)
            return gap > 0 ? gap : nil
        }
    }

    static func estimatedWindow(since latest: Date, intervals: [TimeInterval]) -> EstimatedResetWindow? {
        let sorted = intervals.filter { $0 > 0 && $0.isFinite }.sorted()
        guard sorted.count >= minimumSampleSize,
              let lower = quantile(0.25, of: sorted),
              let upper = quantile(0.75, of: sorted) else {
            return nil
        }
        return EstimatedResetWindow(startsAt: latest.addingTimeInterval(lower),
                                    endsAt: latest.addingTimeInterval(upper))
    }

    private static func quantile(_ fraction: Double, of sorted: [TimeInterval]) -> TimeInterval? {
        guard !sorted.isEmpty else { return nil }
        let position = fraction * Double(sorted.count - 1)
        let low = Int(position.rounded(.down))
        let high = Int(position.rounded(.up))
        return sorted[low] + (sorted[high] - sorted[low]) * (position - Double(low))
    }

    private static func request<T: Decodable>(_ url: URL) async throws -> T {
        var request = URLRequest(url: url)
        // Cloudflare's shared cache already coalesces requests for the API.
        // Avoid a further four-hour device cache for time-sensitive notices.
        request.cachePolicy = .reloadIgnoringLocalCacheData
        request.setValue("application/json", forHTTPHeaderField: "Accept")
        request.timeoutInterval = 15
        let (data, response) = try await URLSession.shared.data(for: request)
        guard let response = response as? HTTPURLResponse else {
            throw ResetForecastError.invalidResponse
        }
        guard response.statusCode == 200 else {
            throw ResetForecastError.unavailable(response.statusCode)
        }
        let decoder = JSONDecoder()
        decoder.keyDecodingStrategy = .convertFromSnakeCase
        decoder.dateDecodingStrategy = .custom { decoder in
            let string = try decoder.singleValueContainer().decode(String.self)
            let formatter = ISO8601DateFormatter()
            formatter.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
            if let date = formatter.date(from: string) { return date }
            formatter.formatOptions = [.withInternetDateTime]
            if let date = formatter.date(from: string) { return date }
            throw DecodingError.dataCorruptedError(
                in: try decoder.singleValueContainer(), debugDescription: "Invalid ISO-8601 date"
            )
        }
        return try decoder.decode(T.self, from: data)
    }
}

private struct StatusResponse: Decodable {
    let data: StatusData
    let meta: ResetMeta
}

private struct StatusData: Decodable {
    let latestReset: ResetRecord?
    let scheduledReset: ScheduledResetRecord?
}

private struct ScheduledResetRecord: Decodable {
    let resetType: String
    let announcedAt: Date
    let scheduledFor: Date?
    let text: String
    let source: ResetSource
}

private struct ResetListResponse: Decodable {
    let data: [ResetRecord]
    let pagination: ResetPagination
}

private struct ResetRecord: Decodable {
    let id: String
    let resetType: String
    let announcedAt: Date
}

private struct ResetSource: Decodable {
    let type: String
    let author: String?
    let url: URL?
}

private struct ResetPagination: Decodable {
    let hasMore: Bool
    let nextCursor: String?
}

private struct ResetMeta: Decodable {
    let generatedAt: Date
}
